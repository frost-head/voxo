/** Builds an <svg> for `name`. */
export function icon(name, { size, className = '' } = {}) {
  const svg = document.createElementNS(SVG_NS, 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('focusable', 'false');
  svg.setAttribute('class', `ico ${className}`.trim());
  if (size) { svg.setAttribute('width', size); svg.setAttribute('height', size); }
  fillIcon(svg, name);
  return svg;
}

function fillIcon(svg, name) {
  const d = ICONS[name];
  svg.replaceChildren();
  if (!d) return;
  const path = document.createElementNS(SVG_NS, 'path');
  path.setAttribute('d', d);
  svg.append(path);
  svg.dataset.icon = name;
}

/** Swaps the icon inside an existing <svg data-icon>. */
export function setIcon(svg, name) {
  if (svg && svg.dataset.icon !== name) fillIcon(svg, name);
}

/** Fills every <svg class="ico" data-icon="…"> already in the page. */
export function hydrateIcons(root = document) {
  for (const svg of root.querySelectorAll('svg[data-icon]')) {
    if (!svg.firstChild) {
      svg.setAttribute('viewBox', '0 0 24 24');
      svg.setAttribute('aria-hidden', 'true');
      fillIcon(svg, svg.dataset.icon);
    }
  }
}
